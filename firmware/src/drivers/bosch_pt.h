/*
 * ВРО-1 / RocketBoard — компенсация давления и температуры Bosch
 *
 * У BMP280 и BME280 расчёт давления и температуры совпадает полностью:
 * одинаковые калибровочные коэффициенты в тех же регистрах и одинаковые
 * формулы. Различаются они только влажностью, которой у BMP280 нет и
 * которая проекту не нужна.
 *
 * Поэтому формулы лежат здесь, а не копируются в оба драйвера. Копия
 * этой арифметики в двух файлах однажды разошлась бы при правке, и
 * высота поехала бы только в одной из сборок — такое ловится тяжело.
 */

#ifndef BOSCH_PT_H
#define BOSCH_PT_H

#include <Arduino.h>

namespace BoschPT {

/* Калибровочные коэффициенты, зашитые в конкретный экземпляр микросхемы.
 * Читаются один раз при инициализации из регистров 0x88..0x9F. */
struct Calib {
    uint16_t T1;
    int16_t  T2, T3;
    uint16_t P1;
    int16_t  P2, P3, P4, P5, P6, P7, P8, P9;

    /* Промежуточная величина из формулы Bosch. Заполняется при расчёте
     * температуры и нужна для расчёта давления, поэтому температуру
     * всегда считают первой. */
    int32_t  t_fine;
};

/* Разбор 24 байт калибровочного блока. false означает, что прочитан
 * мусор: T1 и P1 нулевыми быть не могут. */
bool parseCalib(const uint8_t *raw24, Calib &c);

/* Температура в сотых долях градуса. Побочно заполняет c.t_fine. */
int32_t compensateT(Calib &c, int32_t adc_T);

/* Давление в паскалях.
 *
 * Взят 32-разрядный вариант формулы, а не 64-разрядный: у ATmega32U4
 * нет аппаратного умножения 64 бит, и такой расчёт занял бы в разы
 * больше времени прямо в полётном цикле. Потеря точности — единицы
 * паскалей, то есть доли метра, что для учебной ракеты несущественно. */
uint32_t compensateP(const Calib &c, int32_t adc_P);

} /* namespace BoschPT */

#endif /* BOSCH_PT_H */
