/*
 * ВРО-1 / RocketBoard — интерфейс драйвера инерциального модуля
 *
 * Микросхемы взаимоисключающие: на плате стоит либо ICM-20948, либо
 * MPU9250. Какая именно — задаётся макросом IMU_DRIVER в файле набора
 * из src/hw/. В сборку попадает ровно один файл реализации.
 *
 * Драйвер отдаёт сырые отсчёты и масштабные коэффициенты, а пересчёт в
 * физические величины, калибровку нуля и фильтрацию делает sensors.cpp.
 * Так чип-зависимого кода остаётся минимум, и добавить третью микросхему
 * будет стоить одного нового файла.
 */

#ifndef IMU_H
#define IMU_H

#include <Arduino.h>

namespace ImuDriver {

/* Проверка WHO_AM_I и настройка диапазонов из config.h.
 * false означает, что микросхема не найдена или отвечает не тем. */
bool init(void);

/* Сырые отсчёты: три оси акселерометра, затем три оси гироскопа. */
bool readRaw(int16_t *accel, int16_t *gyro);

/* Сколько отсчётов приходится на 1 g и на 1 °/с при выбранном диапазоне. */
float accelScale(void);
float gyroScale(void);

/* Название микросхемы для отладочного вывода и документации. */
const __FlashStringHelper *name(void);

} /* namespace ImuDriver */

#endif /* IMU_H */
