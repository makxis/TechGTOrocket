/*
 * ВРО-1 / RocketBoard — полётный журнал на MicroSD
 *
 * Пункт 18 ТЗ: каждый запуск создаёт отдельный файл FLTnnnn.CSV,
 * существующие файлы не перезаписываются.
 * Пункт 19 ТЗ: формат CSV.
 * Пункт 20 ТЗ: запись не должна блокировать автомат полёта,
 * бесконечное ожидание ответа карты запрещено.
 * Пункт 36 ТЗ: отсутствие карты — штатный режим работы.
 */

#ifndef SD_LOGGER_H
#define SD_LOGGER_H

#include "types.h"
#include "config.h"

/* Наличие MicroSD задаётся набором железа (HAS_SD в src/hw/). При HAS_SD == 0
 * библиотека SD не попадает в сборку вовсе, экономя 10 920 байт флеша,
 * а все функции ниже становятся пустыми. Остальной код при этом не меняется
 * ни на строку — именно такой независимости требует п. 5 ТЗ. */

namespace SdLogger {

/* Попытка инициализации. Отсутствие карты не считается ошибкой
 * и не мешает переходу в READY (п. 7 ТЗ). */
void init(void);

/* Записать строку телеметрии. Если карты нет, вызов ничего не делает. */
void writeRecord(const TelemetryRecord &rec);

/* Записать событие (п. 33 ТЗ). */
void writeEvent(uint32_t timeMs, uint8_t ev);

/* Сбросить буфер на карту. Вызывается редко: каждый сброс — это
 * обращение к карте, а они дороги по времени. */
void flush(void);

/* Корректно закрыть файл после посадки (п. 18.7 ТЗ). */
void close(void);

uint8_t status(void);      /* enum SubsystemStatus */
bool    isAvailable(void);

} /* namespace SdLogger */

#endif /* SD_LOGGER_H */
