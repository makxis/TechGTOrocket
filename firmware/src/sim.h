/*
 * ВРО-1 / RocketBoard — воспроизведение тестового профиля полёта
 *
 * Пункт 43 ТЗ: должен быть режим, в котором Flight Manager получает
 * данные не от реальных датчиков, а из заранее подготовленного набора.
 * Это позволяет проверить, не поднимая ракету в воздух:
 *   - момент обнаружения старта;
 *   - переходы состояний;
 *   - обнаружение апогея;
 *   - выдачу команды на раскрытие;
 *   - обнаружение посадки.
 *
 * Профиль не записан таблицей, а считается на лету интегрированием:
 * так он реагирует на поведение самой программы. Пока система спасения
 * не сработала, модель падает свободно и разгоняется; после раскрытия
 * переходит на установившуюся скорость снижения под парашютом. Таблица
 * такой обратной связи не дала бы, и проверка «апогей не пойман» на ней была бы невозможна.
 *
 * Автомат полёта о подмене не знает: он получает ту же структуру
 * SensorData, что и от настоящих датчиков.
 */

#ifndef SIM_H
#define SIM_H

#include "types.h"
#include "config.h"

namespace Sim {

/* Запустить прогон. Вызывается только из сервисного режима в READY. */
void start(uint32_t nowMs);

/* Идёт ли прогон прямо сейчас. Пока идёт, главный цикл не опрашивает
 * настоящие датчики. */
bool active(void);

/* Заполнить показания из модели вместо датчиков. */
void fill(SensorData &d, uint32_t nowMs);

/* Завершить прогон досрочно. */
void stop(void);

} /* namespace Sim */

#endif /* SIM_H */
