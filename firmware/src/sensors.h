/*
 * ВРО-1 / RocketBoard — работа с датчиками
 *
 * Пункт 4.1 ТЗ: обязательны акселерометр и барометр, гироскоп для
 * дополнительного анализа.
 * Пункт 9 ТЗ: калибровка базового давления площадки.
 * Пункт 34 ТЗ: проверка диапазонов и фильтрация выбросов.
 *
 * Установленное железо подтверждено на стенде 21.09.2026:
 *   ICM-20948 на 0x68 (НЕ MPU9250, карта регистров другая)
 *   BMP280    на 0x77
 * Подробности в docs/HARDWARE.md.
 */

#ifndef SENSORS_H
#define SENSORS_H

#include "types.h"

namespace Sensors {

/* Поиск и настройка датчиков. Возвращает false, если не поднялся
 * хотя бы один обязательный датчик. Конкретика — в флагах диагностики. */
bool init(void);

/* Калибровка по п. 9 ТЗ: усреднение давления на площадке и снятие
 * нуля гироскопа. Вызывается один раз при старте, блокирующая —
 * это допустимо, полёт ещё не начался. */
void calibrateGround(void);

/* Чтение инерциального модуля. Быстрое, вызывается на SENSOR_RATE_HZ. */
void readImu(SensorData &d);

/* Чтение барометра. Заметно медленнее IMU, поэтому вызывается реже,
 * на BARO_RATE_HZ. Внутри — проверка диапазона и фильтрация (п. 34 ТЗ). */
void readBaro(SensorData &d, uint32_t nowMs);

/* Установка и подстройка нуля высоты на площадке. Вызывать на каждом
 * проходе цикла, пока ракета в READY и не идёт прогон модели. Не
 * блокирует. Подробности — у параметров GROUND_* в config.h. */
void updateGround(const SensorData &d, uint32_t nowMs);

/* Предполётное обнуление: заново поставить ноль высоты. Вызывать на земле в
 * READY, когда показания «уехали» (температура, погода). Ноль снова
 * устанавливается быстро: ракету нужно продержать неподвижной около 8 с
 * (GROUND_STILL_MS + GROUND_ZERO_AVG_MS), потом высота снова 0, и придёт
 * событие GROUND_ZERO. Пока идёт установка, светодиод мигает как при старте. */
void rezero(uint32_t nowMs);

/* Поставлен ли ноль после того, как ракету перестали трогать. */
bool groundZeroSet(void);

/* Базовое давление площадки, Па. Ноль означает, что калибровки не было. */
int32_t groundPressure(void);

} /* namespace Sensors */

#endif /* SENSORS_H */
