#endif

/* Если разброс давления при калибровке больше этого, взводим
 * диагностический флаг (п. 9 ТЗ). */
#ifndef BARO_CALIB_MAX_SPREAD_PA
#define BARO_CALIB_MAX_SPREAD_PA    120L
#endif

/* --- Ноль высоты на площадке ---
 *
 * Калибровка при включении (выше) даёт ноль сразу, чтобы старт ловился
 * даже без ожидания. Но при включении ракету обычно держат в руках, а
 * до старта она стоит минуты: давление за это время уезжает. Поэтому
 * настоящий ноль ставится, когда ракету перестали трогать, а затем
 * медленно подстраивается, пока она стоит неподвижно. На старте
 * подстройка замирает сама: ракета начинает двигаться.
 *
 * Неподвижность проверяется по каждой оси акселерометра, а не по модулю:
 * наклон в руках модуль не меняет, а оси меняет. 0,1 g — это около 6°.
 * Раскачка ветром на штанге (2-3°) этот допуск проходит, руки — нет. */
#ifndef GROUND_STILL_TOL_G
#define GROUND_STILL_TOL_G          0.10f  /* ТРЕБУЕТ ИСПЫТАНИЙ */
#endif

/* Сколько плата должна пролежать неподвижно, прежде чем ей верить. */
#ifndef GROUND_STILL_MS
#define GROUND_STILL_MS             3000
#endif

/* Сколько усредняем давление для нуля после того, как плату положили. */
#ifndef GROUND_ZERO_AVG_MS
#define GROUND_ZERO_AVG_MS          5000
#endif

/* Если ноль так и не удалось поставить, через столько миллисекунд после
 * включения взводим флаг ERROR_BARO_CALIB. Ракета при этом остаётся в
 * READY и старт ловит, но ноль высоты — от калибровки при включении. */
#ifndef GROUND_ZERO_TIMEOUT_MS
#define GROUND_ZERO_TIMEOUT_MS      30000UL
#endif

/* Подстройка нуля идёт с постоянной времени около 41 с (шаг 1/1024 на
 * отсчёт барометра, см. Sensors::updateGround). Отставание от дрейфа
 * давления равно скорости дрейфа, умноженной на это время: погода
 * (около 0,01 Па/с) даёт доли паскаля, то есть ничего. */

/* Сколько измерений усредняем для нуля гироскопа. На стенде замерено
 * смещение до -0,65 °/с, так что калибровка обязательна. */
