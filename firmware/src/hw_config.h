/*
 * ВРО-1 / RocketBoard — выбор набора железа
 *
 * Пункт 27 ТЗ описывает четыре допустимые конфигурации, а п. 1 требует,
 * чтобы ПО было единым для всех. Одной прошивкой на ATmega32U4 это не
 * решается: библиотека SD занимает 10 920 байт флеша из 28 672 доступных
 * (замерено 21.09.2026), и сборка «всё сразу» выходит за предел платы.
 *
 * Поэтому набор выбирается на этапе компиляции. Полётный код при этом
 * остаётся общим: автомат полёта, система спасения и телеметрия ничего
 * не знают о том, какой набор собран, и работают одинаково во всех
 * вариантах — ровно этого требует п. 27.
 *
 * Отличаются только подключаемые драйверы и то, какие подсистемы вообще
 * попадают в сборку.
 *
 * ---------------------------------------------------------------------
 *  Как выбрать набор
 * ---------------------------------------------------------------------
 *
 * Либо флагом при сборке:
 *
 *     arduino-cli compile --fqbn arduino:avr:leonardo \
 *         --build-property "compiler.cpp.extra_flags=-DHW_PROFILE=4" firmware
 *
 * Либо готовым профилем из sketch.yaml, что проще и не даёт ошибиться:
 *
 *     arduino-cli compile --profile d_full
 *
 * Либо правкой одной строки HW_PROFILE ниже.
 */

#ifndef HW_CONFIG_H
#define HW_CONFIG_H

/* ------------------------------------------------------------------ */
/*  Наборы по п. 27 ТЗ                                                 */
/* ------------------------------------------------------------------ */

#define HW_PROFILE_A  1   /* датчики + сервопривод                     */
#define HW_PROFILE_B  2   /* датчики + сервопривод + MicroSD           */
#define HW_PROFILE_C  3   /* датчики + сервопривод + HC-12             */
#define HW_PROFILE_D  4   /* датчики + сервопривод + MicroSD + HC-12   */

/* Набор по умолчанию — A: именно он соответствует тому, что физически
 * собрано на стенде на 21.09.2026. Ни карты, ни радиомодуля пока нет. */
#ifndef HW_PROFILE
#define HW_PROFILE HW_PROFILE_A
#endif

/* ------------------------------------------------------------------ */
/*  Опознавательные номера драйверов                                   */
/* ------------------------------------------------------------------ */

/* Инерциальный модуль. Микросхемы взаимоисключающие: стоит либо одна,
 * либо другая. */
#define IMU_DRIVER_ICM20948  1   /* проверен на железе 21.09.2026 */
#define IMU_DRIVER_MPU9250   2   /* НЕ ПРОВЕРЕН, экземпляра нет   */

/* Барометр. */
#define BARO_DRIVER_BMP280   1   /* проверен на железе 21.09.2026 */
#define BARO_DRIVER_BME280   2   /* НЕ ПРОВЕРЕН, экземпляра нет   */

/* ------------------------------------------------------------------ */
/*  Подключение выбранного набора                                      */
/* ------------------------------------------------------------------ */

#if   HW_PROFILE == HW_PROFILE_A
#include "hw/hw_a.h"
#elif HW_PROFILE == HW_PROFILE_B
#include "hw/hw_b.h"
#elif HW_PROFILE == HW_PROFILE_C
#include "hw/hw_c.h"
#elif HW_PROFILE == HW_PROFILE_D
#include "hw/hw_d.h"
#else
#error "Неизвестный HW_PROFILE. Допустимы значения 1..4, см. hw_config.h"
#endif

/* ------------------------------------------------------------------ */
/*  Умолчания                                                          */
/* ------------------------------------------------------------------ */

/* Файл набора может задать не всё. Чего не задал — берётся отсюда.
 * Все определения под #ifndef, иначе они молча перекрывали бы значения
 * из файла набора и из флагов -D. */

#ifndef HAS_SD
#define HAS_SD      0
#endif

#ifndef HAS_RADIO
#define HAS_RADIO   0
#endif

#ifndef HAS_SERVO
#define HAS_SERVO   1
#endif

/* Наземный сервисный режим по п. 40 ТЗ. Управляется по USB Serial,
 * поэтому без отладочного вывода смысла не имеет. Вынесен в отдельный
 * флаг, чтобы его можно было выключить независимо — это понадобилось
 * при поиске зависания на стенде. */
#ifndef HAS_SERVICE_MODE
#define HAS_SERVICE_MODE  DEBUG_SERIAL_ENABLED
#endif

#ifndef IMU_DRIVER
#define IMU_DRIVER  IMU_DRIVER_ICM20948
#endif

#ifndef BARO_DRIVER
#define BARO_DRIVER BARO_DRIVER_BMP280
#endif

/* ------------------------------------------------------------------ */
/*  Проверки согласованности                                           */
/* ------------------------------------------------------------------ */

/* Без системы спасения ракета не садится, а разбивается. Собрать такую
 * прошивку можно только осознанно, поэтому нужен явный флаг. */
#if !HAS_SERVO && !defined(ALLOW_NO_RECOVERY)
#error "Сборка без системы спасения. Если это осознанно, задайте -DALLOW_NO_RECOVERY"
#endif

#if IMU_DRIVER != IMU_DRIVER_ICM20948 && IMU_DRIVER != IMU_DRIVER_MPU9250
#error "Неизвестный IMU_DRIVER"
#endif

#if BARO_DRIVER != BARO_DRIVER_BMP280 && BARO_DRIVER != BARO_DRIVER_BME280
#error "Неизвестный BARO_DRIVER"
#endif

#endif /* HW_CONFIG_H */
