/*
 * ВРО-1 / RocketBoard — контроль напряжения батареи
 *
 * Делитель на A2 (см. pins.h) измеряет напряжение батареи до стабилизатора
 * L7805. Для «Кроны» 9 В это около 3 В на выводе. Низкое напряжение
 * взводит некритичный флаг ERROR_POWER (п. 28 ТЗ): полёт он не запрещает,
 * но по телеметрии и индикации видно, что батарею пора менять.
 */

#ifndef POWER_H
#define POWER_H

#include <stdint.h>

namespace Power {

void  init(void);

/* Вызывать из главного цикла. Внутри сама выдерживает период. */
void  update(uint8_t flightState, uint32_t nowMs);

/* Последнее измеренное напряжение батареи, В. 0 — ещё не измерено. */
float volts(void);

/* То же в сотых долях вольта, целым числом (911 = 9,11 В). Считается без
 * плавающей арифметики: ею платят флешем, а в полётной сборке запас крошечный. */
uint16_t centivolts(void);

} /* namespace Power */

#endif
