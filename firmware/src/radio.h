/*
 * ВРО-1 / RocketBoard — радиотелеметрия через HC-12
 *
 * Пункт 22 ТЗ: сокращённый текстовый пакет, завершаемый переводом строки.
 * Пункт 23 ТЗ: отсутствие, отключение или неисправность радиомодуля
 * не должны менять логику полёта.
 */

#ifndef RADIO_H
#define RADIO_H

#include "types.h"

namespace Radio {

void init(void);

/* Отправить пакет телеметрии. Если в буфере передатчика не хватает
 * места, пакет молча пропускается: ждать освобождения буфера нельзя,
 * это сорвало бы тайминги полётного цикла (пп. 23 и 31 ТЗ). */
void sendRecord(const TelemetryRecord &rec);

/* Отправить событие (п. 33 ТЗ). Если места в буфере передатчика нет,
 * событие встаёт в короткую очередь и уходит позже из update(). */
void sendEvent(uint32_t timeMs, uint8_t ev);

/* Дослать отложенные события. Вызывать на каждом проходе цикла. */
void update(void);

/* Команды с земли (кадр !номер|команда*CRC, см. cmdframe.h). Доступны
 * только при HAS_RADIO_SERVICE, иначе возвращают false.
 *
 * takeCommand отдаёт принятую команду один раз и только пока она свежая
 * (не старше 2 с): накопившееся за время полёта исполнять нельзя.
 * sendAck отправляет подтверждение "@ACK|номер|команда*CRC". */
bool takeCommand(uint8_t &seq, char &cmd, uint32_t nowMs);

/* Счётчики приёма для диагностики (видны в отладочной строке USB):
 * сколько байт пришло с радио, сколько кадров команд разобрано верно и
 * сколько строк с '!' отвергнуто (CRC, формат). Без радиокоманд всегда 0. */
uint32_t rxBytes(void);
uint16_t rxFrames(void);
uint16_t rxBad(void);
bool sendAck(uint8_t seq, char cmd);

uint8_t  status(void);      /* enum SubsystemStatus */

/* Сколько пакетов и событий было пропущено из-за переполнения буфера.
 * Нужно для разбора полёта: расхождение номеров пакетов на земле
 * может объясняться и этим, а не только потерей радиосвязи. */
uint16_t droppedCount(void);

} /* namespace Radio */

#endif /* RADIO_H */
