/*
 * ВРО-1 / RocketBoard — отладочный вывод
 *
 * Пункт 39 ТЗ: отладочный вывод не должен нарушать тайминги.
 * Пункт 2 ТЗ: программа работает автономно, без подключённого компьютера.
 *
 * ---------------------------------------------------------------------
 *  История этого файла, чтобы никто не повторил
 * ---------------------------------------------------------------------
 *
 * Изначально здесь стояла проверка `Serial.availableForWrite() >= n`
 * перед каждой печатью. Замысел был защитить полётный цикл от
 * блокировки на записи в USB.
 *
 * Замысел оказался вредным, причём дважды.
 *
 * Во-первых, защищать было не от чего. В ядре arduino:avr 1.8.8:
 *
 *   - `Serial_::write` при закрытом порте (`lineState == 0`) сразу
 *     возвращает ноль и ничего не ждёт;
 *   - `USB_Send` имеет собственный таймаут 250 мс и возвращает -1,
 *     то есть бесконечно висеть не может в принципе.
 *
 * Во-вторых, проверка создавала взаимную блокировку. `availableForWrite`
 * возвращает ноль, когда банк конечной точки недоступен для записи.
 * Пока он ноль, проверка запрещает печать; раз печати нет, `USB_Send`
 * не вызывается; раз он не вызывается, банк не освобождается. Вывод
 * умолкал навсегда, хотя программа при этом работала: плата исправно
 * принимала новую прошивку, то есть USB-стек был жив.
 *
 * Именно это выглядело на стенде 21.09.2026 как «вспышки зависаний»:
 * несколько заливок подряд без единой строки в порт, затем столько же
 * подряд без единого отказа. На поиск ушло много времени, а искали не
 * там: под подозрением побывали сервопривод, питание, шина I2C и даже
 * безобидная правка в главном цикле.
 *
 * Отдельная ловушка по дороге: порог был задан в 80 байт, тогда как
 * конечная точка USB у ATmega32U4 отдаёт не больше 64. Условие не
 * выполнялось никогда.
 *
 * ---------------------------------------------------------------------
 *  Как сейчас
 * ---------------------------------------------------------------------
 *
 * Печатаем без всяких проверок, полагаясь на само ядро. Худшее, что
 * может случиться, — задержка 250 мс, если компьютер открыл порт и
 * перестал вычитывать.
 *
 * В полётных сборках этого не случится вовсе: там `DEBUG_SERIAL_ENABLED`
 * равен нулю, и печать вырезана целиком на этапе компиляции. Отладочный
 * вывод остаётся только в наборах A и C, которыми работают на столе.
 *
 * Макрос и функция сохранены, чтобы места вызова остались читаемыми и
 * чтобы при необходимости сюда можно было вернуть настоящую проверку —
 * но уже основанную на состоянии линии, а не на размере буфера.
 */

#ifndef DBG_H
#define DBG_H

#include <Arduino.h>
#include "config.h"

#if DEBUG_SERIAL_ENABLED

/* Печатать можно всегда: ядро само не даст заблокироваться дольше
 * 250 мс и само отбросит вывод при закрытом порте. */
inline bool dbgHasRoom(uint8_t)
{
    return true;
}

#define DBG_NEED(n)  do { (void)(n); } while (0)

#else

inline bool dbgHasRoom(uint8_t) { return false; }
#define DBG_NEED(n)  do { return; } while (0)

#endif /* DEBUG_SERIAL_ENABLED */

#endif /* DBG_H */
