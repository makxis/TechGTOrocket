/*
 * ВРО-1 / RocketBoard — распиновка
 *
 * Источник: схема DevBoard_Std_A3.pdf. Сверено 21.09.2026 —
 * пункт 47.2 ТЗ закрыт.
 *
 * ВАЖНО про имена цепей. На схеме имена цепей у разъёмов не совпадают
 * с именами выводов Arduino. Например, цепь с подписью «A2» на разъёме J8
 * приходит на PF6, а это вывод A1 по нумерации Arduino. Ниже везде
 * указаны номера ИМЕННО в нумерации Arduino — те, что надо передавать
 * в pinMode и analogRead.
 *
 * Соответствие выводов Pro Micro (U4) по схеме:
 *
 *   конт.  порт   цепь на схеме      вывод Arduino
 *   -----  -----  ----------------   -------------
 *     1    PD3    TX                 D1
 *     2    PD2    RX                 D0
 *     5    PD1    SDA                D2
 *     6    PD0    SCL                D3
 *     7    PD4    CS (MicroSD)       D4
 *     8    PC6    LED                D5
 *     9    PD7    SERVO1             D6
 *    10    PE6    SET (радио)        D7
 *    11    PB4    BUZZER             D8
 *    12    PB5    SERVO2             D9
 *    13    PB6    D10                D10
 *    14    PB2    MOSI               D16
 *    15    PB3    MISO               D14
 *    16    PB1    SCK                D15
 *    17    PF7    A0                 A0
 *    18    PF6    A2                 A1
 *    19    PF5    VBAT               A2
 *    20    PF4    BUTTON             A3
 */

#ifndef PINS_H
#define PINS_H

/* ---- Шина I2C ----------------------------------------------------- */
/* У ATmega32U4 выводы TWI заданы аппаратно. Приведены для документации,
 * библиотека Wire берёт их сама. */
#define PIN_I2C_SDA          2   /* PD1 */
#define PIN_I2C_SCL          3   /* PD0 */

/* ---- Сервоприводы (п. 4.2 ТЗ) ------------------------------------- */
/* Разъёмы J4 и J6, оба запитаны от +5 В со стабилизатора L7805. */
#define PIN_SERVO_1          6   /* PD7, цепь SERVO1, разъём J4 */
#define PIN_SERVO_2          9   /* PB5, цепь SERVO2, разъём J6 */

#define PIN_SERVO_RECOVERY   PIN_SERVO_1

/* ---- Индикация (п. 29 ТЗ) ----------------------------------------- */
/* Светодиод D2 на плате через резистор R5 1 кОм. На разъём J7 выведен
 * второй светодиод через R6 1 кОм — на той же цепи. */
#define PIN_LED              5   /* PC6 */

/* Кнопка на разъёме J5, подтянута резистором R3 10 кОм к +5 В. */
#define PIN_BUTTON          A3   /* PF4 */

/* Пьезоизлучатель LS1 через резистор R4 100 Ом.
 * На схеме присутствует; наличие на конкретной ревизии платы проверить. */
#define PIN_BUZZER           8   /* PB4 */
#define HAS_BUZZER           0   /* ТРЕБУЕТ ПРОВЕРКИ на живой плате */

/* ---- MicroSD по SPI (п. 4.5 ТЗ), разъём J9 ------------------------ */
/* Выводы SPI у ATmega32U4 заданы аппаратно, настраивается только выбор
 * кристалла. Разъём J9 по схеме: CS, SCK, MOSI, MISO, +5V, GND. */
#define PIN_SD_CS            4   /* PD4, цепь CS */
#define PIN_SPI_SCK         15   /* PB1 */
#define PIN_SPI_MISO        14   /* PB3 */
#define PIN_SPI_MOSI        16   /* PB2 */

/* ---- Радиомодуль (п. 4.3 ТЗ) -------------------------------------- */
/* На плате два альтернативных посадочных места под радиомодуль:
 * U2 — HC-12, U3 — SV610. Обоим идут одни и те же цепи TX, RX, SET,
 * поэтому программе различать их не требуется.
 *
 * Радио висит на аппаратном UART: у ATmega32U4 это Serial1 на D0/D1,
 * который не конфликтует с отладочным выводом по USB. */
#define PIN_RADIO_RX         0   /* PD2, D0, RX МК  <- TX радиомодуля */
#define PIN_RADIO_TX         1   /* PD3, D1, TX МК  -> RX радиомодуля */
#define PIN_RADIO_SET        7   /* PE6, цепь SET */

/* ---- Контроль питания --------------------------------------------- */
/*
 * Делитель напряжения батареи: R1 = 20 кОм от BAT к точке измерения,
 * R2 = 10 кОм от неё на землю. Коэффициент деления 1/3.
 *
 * Подтверждено расчётом по показаниям тестового скетча, который был
 * залит на плату до начала работ: он печатал «ADC raw: 289  Battery
 * voltage: 4.23 V».
 *
 *     289 / 1023 x 5 В x 3 = 4,238 В
 *
 * Совпадение до сотых подтверждает и делитель, и то, что опорное
 * напряжение АЦП равно напряжению питания. Пункт 47.5 ТЗ закрыт.
 */
/* Делитель стоит ЗА диодом SS14, то есть измеряется напряжение на входе
 * стабилизатора L7805. Сверка мультиметром 29.09.2026: на клеммах батареи
 * 8,53 В, плата показывает 8,08 В (падение на диоде около 0,45 В). Для запаса
 * по стабилизатору это как раз нужное число, калибровка не требуется. */
#define PIN_VBAT            A2   /* PF5, цепь VBAT */
#define VBAT_DIVIDER         3.0f
#define VBAT_ADC_REF_V       5.0f
#define HAS_VBAT_SENSE       1   /* контроль напряжения, src/power.cpp */

/* ---- Питание ------------------------------------------------------ */
/* Вход 9 В (разъёмы J1, J3) через диод SS14 и стабилизатор L7805
 * даёт +5 В. Сервоприводы питаются от той же шины +5 В, поэтому
 * бросок тока привода просаживает питание всей платы.
 *
 * Это не теория: 21.09.2026 подключение сервопривода к плате под
 * напряжением привело к зависанию. Привод подключать до подачи питания. */

/* ---- Датчики на шине I2C ------------------------------------------ */
/*
 * На плате предусмотрены два альтернативных посадочных места:
 *   U5 — GY-91      (MPU9250 + BMP280)
 *   U6 — IMU-10DOF  (ICM-20948 + BMP280)
 *
 * На имеющемся экземпляре установлен вариант U6: WHO_AM_I = 0xEA.
 * Именно поэтому драйверы вынесены в отдельные файлы и выбираются
 * макросом IMU_DRIVER — см. src/hw_config.h и docs/HARDWARE.md.
 *
 * Адреса подтверждены сканированием шины 21.09.2026.
 */
#define IMU_I2C_ADDR      0x68   /* ICM-20948, SA0 на земле */
#define BARO_I2C_ADDR     0x77   /* BMP280, CSB/SDO на питании */

#endif /* PINS_H */
