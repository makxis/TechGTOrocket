/*
 * ВРО-1 / RocketBoard — система спасения
 *
 * Пункт 13 ТЗ: команда выдаётся один раз, повторных переключений привода
 * на каждом цикле быть не должно.
 * Пункт 40 ТЗ: наземный сервисный режим проверки привода.
 */

#ifndef RECOVERY_H
#define RECOVERY_H

#include "types.h"

namespace Recovery {

void init(void);

/* Перевести в готовность. Вызывается при переходе в READY. */
void arm(void);

/* Выдать команду на раскрытие. Повторные вызовы игнорируются —
 * прямое требование п. 13 ТЗ. Параметр backup различает штатное
 * раскрытие по апогею и резервное по п. 14 ТЗ. */
void deploy(bool backup);

/* Вызывается каждый цикл. Снимает питание с привода по истечении
 * времени удержания. Ничего не блокирует. */
void update(uint32_t nowMs);

uint8_t  state(void);
bool     isDeployed(void);

/* Для диагностики: угол, выданный приводу, или -1, если привод отпущен
 * (питание импульсов снято), -2 если привода в сборке нет. */
int16_t  servoCommand(void);

/* Время срабатывания от включения, мс. Ноль, если не срабатывала. */
uint32_t deployTimeMs(void);

/* Сервисный режим по п. 40 ТЗ. Вызывать только на земле:
 * в полёте вход в него исключён проверкой состояния автомата. */
void serviceSetAngle(uint8_t angle);

} /* namespace Recovery */

#endif /* RECOVERY_H */
